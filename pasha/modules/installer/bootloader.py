import logging
import os
import sys
import shutil

from pasha import exceptions, target, utils
from pasha.modules.base import ModuleBase


class Bootloader(ModuleBase):
    def __init__(self, state, config, stage):
        self.state = state
        self.config = config
        self.stage = stage

        self.logging = logging.getLogger(__name__)
        self.kernel_args = self.stage.kernel_args
        self.uefi = self.stage.get("uefi", "systemd-boot")
        self.uefi_driver = self.stage.get("uefi_driver", "")
        self.rootfs = self.state.workspace.joinpath(f"{self.config.name}/rootfs")

    def run(self):
        self.logging.info("Installing boot loader")

        utils.run_chroot_command(
            ["bootctl", "install", "--no-variables", "--entry-token", "os-id"],
            self.rootfs,
            efi=self.rootfs,
            boot=self.rootfs,
        )

        # Set timeout for boot menu
        with open(self.rootfs.joinpath("efi/loader/loader.conf"), "w") as f:
            f.write("# Auto-generated by ruck\n")
            f.write("timeout 3\n")

        if self.uefi == "systemd-boot":
            # Install ext4 file system driver for UEFI
            if self.uefi_driver == "ext4":
                self.logging.info("Install ext4 file system driver for UEFI")
                shutil.copytree(
                    self.rootfs.joinpath("usr/share/edk2/drivers"),
                    self.rootfs.joinpath("efi/EFI/systemd/drivers"),
                    dirs_exist_ok=True,
                )
        elif self.uefi == "grub-efi":
            cmd = ["cp", "-rf", "/usr/lib/ostree-grub/grub", "/boot"]
            utils.run_chroot_command(
                cmd,
                self.rootfs,
                efi=self.rootfs,
                boot=self.rootfs,
            )

            cmd = ["rm", "-rf", "/efi/EFI/BOOT"]
            utils.run_chroot_command(
                cmd,
                self.rootfs,
                efi=self.rootfs,
                boot=self.rootfs,
            )

            cmd = ["cp", "-rf", "/usr/lib/ostree-grub/EFI", "/efi"]
            utils.run_chroot_command(
                cmd,
                self.rootfs,
                efi=self.rootfs,
                boot=self.rootfs,
            )

        # Should be only one kernel.
        for d in self.rootfs.glob("boot/vmlinuz-*"):
            kver = d.name.removeprefix("vmlinuz-")

        cmdline = self.rootfs.joinpath("etc/kernel/cmdline")
        with open(cmdline, "w") as f:
            f.write(self.kernel_args)

        utils.run_chroot_command(
            ["kernel-install", "add", kver, f"/boot/vmlinuz-{kver}"],
            self.rootfs,
            efi=self.rootfs,
            boot=self.rootfs,
        )


class BootloaderOstree(ModuleBase):
    def __init__(self, state, config, stage):
        self.state = state
        self.config = config
        self.stage = stage

        self.logging = logging.getLogger(__name__)
        self.uefi = self.stage.get("uefi", "systemd-boot")
        self.uefi_driver = self.stage.get("uefi_driver", "")
        self.rootfs = self.state.workspace.joinpath(f"{self.config.name}/rootfs")

    def run(self):
        self.logging.info("Installing boot loader for OSTree.")

        for d in self.rootfs.glob("ostree/deploy/elxr/deploy/*.0"):
            repo_root = d
        utils.run_chroot_command(
            [
                "bootctl",
                "install",
                "--boot-path",
                "/boot",
                "--no-variables",
                "--entry-token",
                "os-id",
            ],
            repo_root,
            efi=self.rootfs,
            boot=self.rootfs,
        )

        self.logging.info("Configuring boot loader.")
        # Set timeout for boot menu
        with open(self.rootfs.joinpath("efi/loader/loader.conf"), "w") as f:
            f.write("# Auto-generated by ruck\n")
            f.write("timeout 3\n")

        # Should be only elxr directory.
        for d in self.rootfs.glob("boot/ostree/elxr-*"):
            elxr_dir = d.name.removeprefix("elxr-")

        if self.uefi == "systemd-boot":
            # Install ext4 file system driver for UEFI
            if self.uefi_driver == "ext4":
                self.logging.info("Install ext4 file system driver for UEFI")
                shutil.copytree(
                    os.path.join(repo_root, "usr/share/edk2/drivers"),
                    self.rootfs.joinpath("efi/EFI/systemd/drivers"),
                    dirs_exist_ok=True,
                )
        elif self.uefi == "grub-efi":
            cmd = ["cp", "-rf", "/usr/lib/ostree-grub/grub", "/boot"]
            utils.run_chroot_command(
                cmd,
                repo_root,
                efi=self.rootfs,
                boot=self.rootfs,
            )

            cmd = ["rm", "-rf", "/efi/EFI/BOOT"]
            utils.run_chroot_command(
                cmd,
                repo_root,
                efi=self.rootfs,
                boot=self.rootfs,
            )

            cmd = ["cp", "-rf", "/usr/lib/ostree-grub/EFI", "/efi"]
            utils.run_chroot_command(
                cmd,
                repo_root,
                efi=self.rootfs,
                boot=self.rootfs,
            )

            if self.rootfs.joinpath(f"boot/ostree/elxr-{elxr_dir}/dtb").exists():
                cmd = ["cp", "-rf", f"/boot/ostree/elxr-{elxr_dir}/dtb", "/efi"]
                utils.run_chroot_command(
                    cmd,
                    repo_root,
                    efi=self.rootfs,
                    boot=self.rootfs,
                )


class BootloaderGrub(ModuleBase):
    def __init__(self, state, config, stage):
        self.state = state
        self.config = config
        self.stage = stage

        self.logging = logging.getLogger(__name__)
        self.mounts = self.config.params.get("mounts", None)
        self.device = self.config.params.get("image", None)
        self.rootfs = self.state.workspace.joinpath(f"{self.config.name}/rootfs")

    def run(self):
        self.logging.info("Setting up grub bootloader")

        if self.device is None:
            raise exceptions.ConfigError("Disk is not specified.")
        if not os.path.exists(self.device):
            raise exceptions.ConfigError(f"{self.device} is not found.")

        try:
            with target.RunInTarget(
                image=self.config.params.image, rootfs=self.rootfs, mounts=self.mounts
            ) as chroot:
                arch = "x86_64-efi"
                if self.config.architecture == "arm64":
                    arch = "arm64-efi"
                chroot.run(["update-grub"])
                chroot.run(
                    [
                        "grub-install",
                        "--uefi-secure-boot",
                        f"--target={arch}",
                        "--no-nvram",
                        "--removable",
                    ]
                )
                chroot.run(["update-grub"])
        except RuntimeError:
            self.logging.error("Unable to run all commands. Exiting!!")
            sys.exit(1)
